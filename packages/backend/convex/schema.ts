import { defineSchema, defineTable } from 'convex/server'
import { v } from 'convex/values'
import { planStateValidator } from './lib/plans'
import {
  appRuleOverrides,
  dictationModeValidator,
  formattingPreferencesValidator,
  inferenceKindValidator,
  platformValidator,
  subscriptionValidator,
  syncPreferencesValidator,
  toneValidator
} from './lib/validators'

/**
 * Document-relational layout: one row per synced record, every table keyed by the owning user and
 * indexed for the lookups the clients perform. Users' own provider credentials are intentionally
 * absent; API keys for a bring-your-own model stay on the device that entered them. The instance's
 * managed-model credentials live in deployment environment variables, never in the database.
 */
export default defineSchema({
  users: defineTable({
    /** Clerk user id (`sub` claim of the session JWT). */
    clerkId: v.string(),
    email: v.optional(v.string()),
    name: v.optional(v.string()),
    imageUrl: v.optional(v.string()),
    /**
     * Where the account is in its lifecycle (see lib/plans.ts). Absent on rows created before the
     * trial existed; they read as `free` until `upsertUser` or the backfill grants their trial.
     */
    plan: v.optional(planStateValidator),
    /** End of the 14-day Pro trial, epoch ms. A scheduled `entitlements.endTrial` flips the state. */
    trialEndsAt: v.optional(v.number()),
    /** Stripe customer (`cus_…`) once the account has been through Checkout. */
    stripeCustomerId: v.optional(v.string()),
    /** Latest Stripe subscription snapshot; written only by the Stripe webhook. */
    subscription: v.optional(subscriptionValidator),
    /** Account-level onboarding. Device-level steps (microphone, shortcut) are repeated per device. */
    onboardingCompletedAt: v.optional(v.number()),
    /** Deprecated: the entry count moved to historyMeta. Kept so existing rows still validate; read once to seed historyMeta. */
    historyCount: v.optional(v.number()),
    onboardingVersion: v.optional(v.number()),
    createdAt: v.number(),
    updatedAt: v.number()
  })
    .index('by_clerkId', ['clerkId'])
    .index('by_stripeCustomerId', ['stripeCustomerId']),

  /**
   * Managed inference consumed per account and calendar month (UTC). One row per (user, period);
   * the gateway checks it before forwarding a request and adds to it afterwards.
   */
  inferenceUsage: defineTable({
    userId: v.id('users'),
    /** `YYYY-MM` in UTC. */
    period: v.string(),
    sttSeconds: v.number(),
    sttRequests: v.number(),
    llmTokens: v.number(),
    llmRequests: v.number(),
    /** Start of the current request-rate window and the requests seen in it. */
    windowStart: v.optional(v.number()),
    windowCount: v.optional(v.number()),
    updatedAt: v.number()
  }).index('by_user_and_period', ['userId', 'period']),

  /**
   * Managed inference per account and UTC day, behind the rolling-week word cap and the daily
   * guardrails of the free tier. One row per (user, day); a week is at most seven reads.
   */
  inferenceDays: defineTable({
    userId: v.id('users'),
    /** `YYYY-MM-DD` in UTC. */
    day: v.string(),
    /** Words in the transcripts the speech model returned. */
    words: v.number(),
    sttSeconds: v.number(),
    /** Transcriptions. */
    dictations: v.number(),
    /** Formatting requests (chat completions and /v1/format). */
    formats: v.number(),
    updatedAt: v.number()
  }).index('by_user_and_day', ['userId', 'day']),

  /**
   * How the instance's managed providers have been answering lately, one row per kind: the
   * unavailable answers in a row and, once there are enough of them, until when the gateway
   * answers `provider_unavailable` itself instead of asking again (the breaker in lib/upstream.ts).
   * Instance-wide by design: a provider that is down is down for every account.
   */
  providerHealth: defineTable({
    kind: inferenceKindValidator,
    failures: v.number(),
    /** Epoch ms; while in the future, requests for this provider are refused at once. */
    openUntil: v.optional(v.number()),
    lastFailureAt: v.optional(v.number()),
    /** `timeout`, `unreachable` or `unavailable`: what the last failure was. */
    lastReason: v.optional(v.string()),
    updatedAt: v.number()
  }).index('by_kind', ['kind']),

  devices: defineTable({
    userId: v.id('users'),
    /** Stable per-install identifier generated by the client. */
    deviceId: v.string(),
    name: v.string(),
    platform: platformValidator,
    appVersion: v.string(),
    lastSeenAt: v.number(),
    createdAt: v.number()
  })
    .index('by_user', ['userId'])
    .index('by_user_and_deviceId', ['userId', 'deviceId']),

  /**
   * Per-device liveness, kept apart from the devices rows: a heartbeat used to patch `lastSeenAt`
   * on the device row, and every `devices.list` subscription re-read its whole result after every
   * heartbeat of every device. Heartbeats write here, at most once per ten minutes per device;
   * `devices.list` and `bootstrap.get` join it for the live last-seen time, so a liveness write
   * re-runs the subscriptions that read it only at the throttle's pace.
   */
  deviceLiveness: defineTable({
    userId: v.id('users'),
    deviceId: v.string(),
    lastSeenAt: v.number()
  }).index('by_user_and_deviceId', ['userId', 'deviceId']),

  /**
   * Desktops with "Phone as microphone" on (docs/phone-microphone.md): what a phone lists. Written
   * when the switch or the device's name changes and at most once a day otherwise, never by a
   * heartbeat; kept apart from `devices` so `devices.list` and `bootstrap.get` never re-run for it.
   */
  micReceivers: defineTable({
    userId: v.id('users'),
    deviceId: v.string(),
    name: v.string(),
    platform: platformValidator,
    registeredAt: v.number()
  }).index('by_user_and_deviceId', ['userId', 'deviceId']),

  /**
   * Phone-microphone signaling: one offer and one answer per link, each deleted once read (the
   * desktop deletes the offer it answers, the phone the answer it takes) and swept after
   * MIC_SIGNAL_TTL_MS. Audio never comes here; it goes peer to peer over WebRTC.
   */
  micSignals: defineTable({
    userId: v.id('users'),
    /** The addressee's deviceId. */
    to: v.string(),
    from: v.string(),
    fromName: v.string(),
    linkId: v.string(),
    kind: v.union(v.literal('offer'), v.literal('answer'), v.literal('decline')),
    /** The complete SDP (ICE gathered, no trickle). Empty on a decline. */
    sdp: v.string(),
    /** Why a link was declined, in one sentence. */
    reason: v.optional(v.string()),
    createdAt: v.number()
  }).index('by_user_and_to', ['userId', 'to']),

  dictionaryEntries: defineTable({
    userId: v.id('users'),
    word: v.string(),
    /** Normalized (trimmed, lower-cased, single-spaced) word used for de-duplication. */
    wordKey: v.string(),
    aliases: v.array(v.string()),
    fuzzy: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number()
  })
    .index('by_user', ['userId'])
    .index('by_user_and_wordKey', ['userId', 'wordKey']),

  snippets: defineTable({
    userId: v.id('users'),
    trigger: v.string(),
    triggerKey: v.string(),
    content: v.string(),
    createdAt: v.number(),
    updatedAt: v.number()
  })
    .index('by_user', ['userId'])
    .index('by_user_and_triggerKey', ['userId', 'triggerKey']),

  appRules: defineTable({
    userId: v.id('users'),
    match: v.string(),
    matchKey: v.string(),
    tone: toneValidator,
    ...appRuleOverrides,
    createdAt: v.number(),
    updatedAt: v.number()
  })
    .index('by_user', ['userId'])
    .index('by_user_and_matchKey', ['userId', 'matchKey']),

  preferences: defineTable({
    userId: v.id('users'),
    formatting: v.optional(formattingPreferencesValidator),
    language: v.optional(v.string()),
    sync: v.optional(syncPreferencesValidator),
    updatedAt: v.number()
  }).index('by_user', ['userId']),

  stats: defineTable({
    userId: v.id('users'),
    totalWords: v.number(),
    totalSessions: v.number(),
    totalSpeechMs: v.number(),
    streakDays: v.number(),
    /** Local calendar day (YYYY-MM-DD) of the last session, as reported by the device. */
    lastSessionDay: v.string(),
    /** Recently counted session ids; lets a device replay `recordSession` without double counting. */
    recentSessionIds: v.optional(v.array(v.string())),
    updatedAt: v.number()
  }).index('by_user', ['userId']),

  historyEntries: defineTable({
    userId: v.id('users'),
    deviceId: v.string(),
    /** Client-generated id of the dictation session; makes pushes idempotent. */
    entryId: v.string(),
    createdAt: v.number(),
    mode: dictationModeValidator,
    rawText: v.optional(v.string()),
    finalText: v.string(),
    wordCount: v.number(),
    speechMs: v.number(),
    appName: v.optional(v.string()),
    provider: v.string(),
    model: v.string(),
    llmUsed: v.boolean()
  })
    .index('by_user_and_createdAt', ['userId', 'createdAt'])
    .index('by_user_and_entryId', ['userId', 'entryId'])
    // Insertion order (`_creationTime` is implicit): the cursor `history.since` pages along, so a
    // device fetches only what arrived since it last asked instead of re-reading a backlog.
    .index('by_user', ['userId']),

  /**
   * One row per account: the number of its historyEntries, maintained by the history mutations so
   * pruning never scans. The count lives here and not on the users row because every authenticated
   * query reads the account row: patching it on every push re-ran all of a user's live
   * subscriptions (devices, preferences, dictionary, snippets, app rules, stats) after every
   * dictation, which was most of Murmur's function-call load on the Convex free plan.
   */
  historyMeta: defineTable({
    userId: v.id('users'),
    count: v.number()
  }).index('by_user', ['userId']),

  /**
   * All-day recording: speech the server transcribed from a device's audio (/v1/timeline/audio),
   * waiting for the account's desktop to pick it up into its timeline. Rows and their audio are
   * deleted after a week.
   */
  timelineChunks: defineTable({
    userId: v.id('users'),
    device: v.string(),
    startedAt: v.string(),
    endedAt: v.string(),
    text: v.string(),
    engine: v.string(),
    rmsDb: v.number(),
    speechRatio: v.number(),
    speakers: v.number(),
    /** Server-side value score (0..1) and why: speech, idea. */
    score: v.optional(v.number()),
    tags: v.optional(v.array(v.string())),
    /** The piece's audio, kept a week so a careful transcript can be made on request. */
    audio: v.optional(v.id('_storage')),
    /** The desktop took the text into its timeline (the row stays for careful transcripts). */
    taken: v.optional(v.boolean()),
    /** The careful transcript, made once on request (/v1/timeline/refine). */
    refinedText: v.optional(v.string())
  })
    .index('by_user', ['userId'])
    .index('by_user_taken', ['userId', 'taken'])
    .index('by_user_device_start', ['userId', 'device', 'startedAt'])
})
