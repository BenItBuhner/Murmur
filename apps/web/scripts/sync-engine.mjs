// Copies the parts of packages/text-engine that /dictate runs into src/lib/engine. The site cannot
// import across its root (Turbopack and OpenNext build from apps/web), so like mic-protocol.ts it
// keeps a copy; engine-sync.test.ts fails when the copy drifts. Run `npm run sync:engine` after
// changing the engine.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const ENTRY = ['cleanup', 'context', 'dictionary', 'format', 'prompt-echo', 'types']
const src = fileURLToPath(new URL('../../../packages/text-engine/src/', import.meta.url))
const out = fileURLToPath(new URL('../src/lib/engine/', import.meta.url))
const HEADER =
  '// Generated by scripts/sync-engine.mjs from packages/text-engine/src; do not edit.\n'

export function closure() {
  const seen = new Set()
  const todo = [...ENTRY]
  while (todo.length) {
    const m = todo.pop()
    if (seen.has(m)) continue
    seen.add(m)
    for (const [, dep] of readFileSync(`${src}${m}.ts`, 'utf8').matchAll(/from '\.\/([\w-]+)'/g))
      todo.push(dep)
  }
  return [...seen].sort()
}

export function expected() {
  return Object.fromEntries(
    closure().map((m) => [`${m}.ts`, HEADER + readFileSync(`${src}${m}.ts`, 'utf8')])
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })
  for (const [name, body] of Object.entries(expected())) writeFileSync(out + name, body)
  console.log(`engine: ${readdirSync(out).length} files in src/lib/engine`)
}
